(ns omkamra.dsp.tests.literals
  "The box a float literal's type travels in (D78).

  The invariant these tests hold is the one the browser depends on: a definition
  the browser will compile — captured from source, generated by a builtin's
  expansion, built by a description transformer, or written into the acceptance
  catalog — contains no bare float literal. On a platform with one number type an
  integral float is the integer it looks like, so a bare one is a silent type
  change waiting to happen; the point of these tests is that it cannot happen
  silently again."
  (:require [clojure.test :refer [deftest is]]
            [omkamra.dsp :as dsp]
            [omkamra.dsp.builtins :as builtins]
            [omkamra.dsp.combinators :as combinators]
            [omkamra.dsp.descriptor :as descriptor]
            [omkamra.dsp.harness.catalog :as catalog]
            [omkamra.dsp.ir :as ir]
            [omkamra.dsp.library.control]
            [omkamra.dsp.library.delay]
            [omkamra.dsp.library.effect]
            [omkamra.dsp.library.envelope]
            [omkamra.dsp.library.filter]
            [omkamra.dsp.library.math]
            [omkamra.dsp.library.noise]
            [omkamra.dsp.library.oscillator]
            [omkamra.dsp.library.pitch]
            [omkamra.dsp.linker :as linker]
            [omkamra.dsp.literals :as literals]))

;; Definitions captured by the test, in the same shape the library uses: the
;; macro records data, and the data is what the assertions read.
(omkamra.dsp/defn captured-float
  [sample]
  (+ sample 1.5))

(omkamra.dsp/defn captured-integral
  [sample]
  (* sample 2.0))

(omkamra.dsp/defn captured-state
  [sample]
  {:state [{:name 'held :init 0.5 :next '(+ held 0.25)}]}
  held)

(omkamra.dsp/defn probe-voice
  [sample detune gate]
  {:process {:controls [{:name 'detune :type :float :default 0.0}
                        {:name 'gate :type :float :default 0.0}]}}
  (* sample detune gate))

(def library-namespaces
  '[omkamra.dsp.library.control omkamra.dsp.library.delay
    omkamra.dsp.library.effect omkamra.dsp.library.envelope
    omkamra.dsp.library.filter omkamra.dsp.library.math omkamra.dsp.library.noise
    omkamra.dsp.library.oscillator omkamra.dsp.library.pitch
    omkamra.dsp.harness.fixtures])

(defn bare-floats
  "Every unboxed float literal inside `form`, with the path it sits at."
  ([form] (bare-floats form []))
  ([form path]
   (cond
     (literals/float-literal? form) []
     (map? form) (mapcat (fn [[k v]] (bare-floats v (conj path k))) form)
     (coll? form) (mapcat (fn [[i v]] (bare-floats v (conj path i)))
                          (map-indexed vector form))
     (and (double? form) (not (integer? form))) [[path form]]
     :else [])))

(defn definition-floats
  "Bare float literals in a definition's body and state transitions."
  [definition]
  (concat (bare-floats (vec (:body definition)))
          (mapcat (fn [[index state]]
                    (when (:next state)
                      (bare-floats (:next state) [:state index :next])))
                  (map-indexed vector (:state definition)))))

(defn library-definitions
  []
  (for [n library-namespaces
        [name v] (ns-publics n)
        :let [value (try @v (catch Throwable _ nil))]
        :when (and (map? value) (= :function (:dsp/kind value)))]
    [(symbol (str n) (str name)) value]))

(deftest an-authored-float-literal-is-boxed-at-capture
  (is (= [(list '+ 'sample (literals/float-literal 1.5))] (vec (:body captured-float)))))

(deftest an-integral-float-is-boxed-at-capture
  ;; The ambiguous kind: `2.0` reads as the integer 2 wherever a platform has
  ;; one number type, so the box is what keeps it a float.
  (is (= [(list '* 'sample (literals/float-literal 2.0))] (vec (:body captured-integral))))
  (is (empty? (definition-floats captured-integral))))

(deftest a-state-transition-boxes-its-float-and-not-its-init
  ;; `:init` is a declared value, typed by the slot it initializes; a `:next` is
  ;; a form, and a form's literals travel.
  (is (= 0.5 (get-in captured-state [:state 0 :init])))
  ;; The author wrote `:next '(+ held 0.25)`, so the captured transition is a
  ;; quoted form; the box is inside it.
  (is (= (list 'quote (list '+ 'held (literals/float-literal 0.25)))
         (get-in captured-state [:state 0 :next])))
  (is (empty? (definition-floats captured-state))))

(deftest a-boxed-float-lowers-to-a-float-constant
  (let [definition (descriptor/normalize
                    {:dsp/kind :function
                     :name 'boxed
                     :params ['sample]
                     :body [(list '* 'sample (literals/float-literal 2.0))]})
        lowered (ir/lower-unit (linker/link definition))
        constants (filter #(and (map? %) (= :const (:op %)))
                          (tree-seq coll? seq (:body lowered)))
        floats (filter #(= :float (:type %)) constants)]
    (is (= [2.0] (mapv :value floats)))
    (is (every? float? (mapv :value floats)))))

(deftest the-box-is-data-and-nothing-else
  (is (not (literals/float-literal? 1.0)))
  (is (literals/float-literal? (literals/float-literal 1.0)))
  (is (= 1.0 (literals/float-literal-value (literals/float-literal 1.0))))
  (is (not (literals/float-literal? {:dsp/float 1.0 :other 2})))
  (is (not (literals/float-literal? {:dsp/float "x"})))
  (is (not (literals/float-literal? {})))
  (is (= {:dsp/float 1.5} (read-string "#dsp/float 1.5"))))

(deftest every-builtin-expansion-boxes-its-floats
  (doseq [[operator entry] builtins/builtins
          :when (:expand entry)
          :let [arity (count (:params (first (:signatures entry))))
                args (mapv #(symbol (str "arg" %)) (range arity))
                expanded ((:expand entry) args)]
          [path value] (bare-floats expanded)]
    (is false (str operator " expands to a bare float " (pr-str value)
                   " at " (pr-str path)))))

(deftest every-library-definition-boxes-its-floats
  (doseq [[id definition] (library-definitions)
          [path value] (definition-floats definition)]
    (is false (str id " has a bare float " (pr-str value) " at " (pr-str path)))))

(deftest every-description-transformer-boxes-its-floats
  (let [guarded (combinators/guard probe-voice {:gate 'detune})
        unisoned (combinators/unison probe-voice {:count 3 :detune 20.0 :gain 2.0})]
    (doseq [[id definition] [['guard guarded] ['unison unisoned]]
            [path value] (definition-floats definition)]
      (is false (str id " generated a bare float " (pr-str value)
                     " at " (pr-str path))))))

(deftest every-catalog-definition-boxes-its-floats
  (doseq [case catalog/cases
          :when (nil? (:definition-var case))
          :when (:definition case)
          [path value] (definition-floats (:definition case))]
    (is false (str (:id case) " has a bare float " (pr-str value) " at " (pr-str path)))))
