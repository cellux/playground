(ns omkamra.dsp.library.doc
  "Render the portable DSP library reference from the descriptors themselves.

  Shape is never hand-maintained: names, parameters, controls, state, and return
  types come from the same descriptors the compiler lowers, so the page cannot
  drift. Only the prose a descriptor cannot carry — latency and modulation
  behaviour — comes from each `dsp/defn` docstring, captured at definition time."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [omkamra.dsp.linker :as linker]))

(def library-namespaces
  "Library namespaces, in reference order."
  '[omkamra.dsp.library.math
    omkamra.dsp.library.oscillator
    omkamra.dsp.library.noise
    omkamra.dsp.library.envelope
    omkamra.dsp.library.filter
    omkamra.dsp.library.delay
    omkamra.dsp.library.control
    omkamra.dsp.library.effect])

(defn definition?
  "True for a CSP definition descriptor bound to a Var."
  [value]
  (and (map? value) (= :function (:dsp/kind value))))

(defn module-definitions
  "The DSP definitions public in `ns-sym` as `[name descriptor]`, linked so that
  `:struct` references and record return types are resolved."
  [ns-sym]
  (->> (ns-publics ns-sym)
       (keep (fn [[name var]]
               (let [value @var]
                 (when (definition? value)
                   (let [unit (linker/link var)]
                     [name (get-in unit [:definitions (:entry unit)])])))))
       (sort-by (comp str first))))

(defn- prose
  "Collapse a docstring's source indentation into one line."
  [text]
  (some-> text str/trim (str/replace #"\s+" " ")))

(defn- scalar-name
  [type]
  (if (keyword? type) (name type) (str type)))

(defn- state-text
  [state]
  (let [type (cond
               (:struct state) (str "struct " (:struct state))
               (:type state) (scalar-name (:type state))
               :else "float")
        size (or (:size state) 1)]
    (str "`" (:name state) "` " type (when (> size 1) (str "[" size "]")))))

(defn- bullet
  [label body]
  (str "- **" label ":** " body))

(defn- render-module
  [ns-sym [name definition]]
  (let [params (:params definition)
        controls (:controls (:process definition))
        states (:state definition)
        doc (prose (:doc definition))]
    (str/join
     "\n"
     (concat
      (cond-> [(str "### `" ns-sym "/" name "`") ""]
        (seq doc) (conj doc ""))
      [(bullet "Parameters"
               (if (seq params)
                 (str/join ", " (map (fn [p]
                                       (str "`" (:name p) "` " (scalar-name (:type p))))
                                     params))
                 "none"))
       (bullet "Controls"
               (if (seq controls)
                 (str/join ", " (map (fn [control] (str "`" (:name control) "`"))
                                     controls))
                 "none (not a process entry)"))
       (bullet "State"
               (if (seq states)
                 (str/join ", " (map state-text states))
                 "none (stateless)"))
       (bullet "Return"
               (if-let [record (:return-record definition)]
                 (str "record `" (:struct-name record) "`")
                 (scalar-name (:return-type definition))))
       (bullet "Entry"
               (if (:process definition)
                 "process entry and callable module"
                 "callable module"))
       ""]))))

(defn render
  "Render the reference page for `namespaces` (default `library-namespaces`)."
  ([] (render library-namespaces))
  ([namespaces]
   (str/join
    "\n"
    (concat
     ["# DSP standard library reference"
      ""
      "<!-- Generated by `omkamra.dsp.library.doc/render`; do not edit by hand. -->"
      ""
      "Every entry is written in the DSP language itself (`.cljc`), composed from"
      "portable builtins, with no target-specific operation. Each namespace's"
      "modules are exercised by the shared acceptance catalog on the interpreter,"
      "JVM, JavaScript, and Wasm."
      ""]
     (mapcat (fn [ns-sym]
               (let [ns-doc (prose (:doc (meta (find-ns ns-sym))))]
                 (concat
                  [(str "## `" ns-sym "`") ""]
                  (when (seq ns-doc) [ns-doc ""])
                  (map (fn [entry] (render-module ns-sym entry))
                       (module-definitions ns-sym)))))
             namespaces)))))

(defn doc-file
  []
  (io/file "src/omkamra/dsp/docs/mvp/LIBRARY.md"))

(defn -main
  [& _]
  (spit (doc-file) (render))
  (println "wrote" (str (doc-file))))

(comment
  (-main))
